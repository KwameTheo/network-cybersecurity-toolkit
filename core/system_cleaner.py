"""
System Cleanup & Disk Space Triage Engine
Analyzes disk usage across Windows drives, calculates reclaimable waste in
temporary folders, Windows Update cache, and crash dumps, and performs safe pruning.
"""

import os
import platform
import shutil
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional
import psutil

from utils.logger import get_logger

logger = get_logger()


@dataclass
class CleanupCategoryInfo:
    key: str
    name: str
    target_path: str
    description: str
    file_count: int
    total_bytes: int
    total_mb: float
    is_accessible: bool

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class DiskSpaceSummary:
    drive_letter: str
    total_gb: float
    used_gb: float
    free_gb: float
    percent_used: float
    categories: List[CleanupCategoryInfo]
    total_reclaimable_mb: float
    total_reclaimable_gb: float

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class CleanupExecutionResult:
    deleted_files: int
    failed_files: int
    freed_bytes: int
    freed_mb: float
    logs: List[str]

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)



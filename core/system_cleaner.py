# DISK USAGE & WASTE ANALYSIS
# =========================================================================

def get_directory_size(dir_path: str) -> tuple[int, int, bool]:
    """
    Scans directory recursively and calculates (file_count, total_bytes, is_accessible).
    """
    if not os.path.exists(dir_path):
        return 0, 0, False

    file_count = 0
    total_bytes = 0
    accessible = True

    try:
        for root, _, files in os.walk(dir_path):
            for f in files:
                f_path = os.path.join(root, f)
                try:
                    total_bytes += os.path.getsize(f_path)
                    file_count += 1
                except (OSError, PermissionError):
                    continue
    except (OSError, PermissionError):
        accessible = False

    return file_count, total_bytes, accessible


def analyze_disk_space(drive: str = "C:\\") -> DiskSpaceSummary:
    """
    Calculates Drive C: capacity and scans all temporary waste categories.
    """
    # Drive partition stats
    try:
        usage = psutil.disk_usage(drive)
        tot_gb = usage.total / (1024 ** 3)
        usd_gb = usage.used / (1024 ** 3)
        fre_gb = usage.free / (1024 ** 3)
        pct_usd = usage.percent
    except Exception:
        tot_gb, usd_gb, fre_gb, pct_usd = 0.0, 0.0, 0.0, 0.0

    targets = get_target_cleanup_directories()
    categories: List[CleanupCategoryInfo] = []
    total_reclaimable_bytes = 0

    for key, info in targets.items():
        p = info["path"]
        f_count, b_size, access = get_directory_size(p)
        total_reclaimable_bytes += b_size
        mb_size = round(b_size / (1024 ** 2), 2)

        categories.append(CleanupCategoryInfo(
            key=key,
            name=info["name"],
            target_path=p,
            description=info["desc"],
            file_count=f_count,
            total_bytes=b_size,
            total_mb=mb_size,
            is_accessible=access
        ))

    rec_mb = round(total_reclaimable_bytes / (1024 ** 2), 2)
    rec_gb = round(total_reclaimable_bytes / (1024 ** 3), 2)

    logger.info(f"Disk Analysis Complete: {rec_mb} MB reclaimable across {len(categories)} categories.")
    return DiskSpaceSummary(
        drive_letter=drive,
        total_gb=round(tot_gb, 2),
        used_gb=round(usd_gb, 2),
        free_gb=round(fre_gb, 2),
        percent_used=round(pct_usd, 1),
        categories=categories,
        total_reclaimable_mb=rec_mb,
        total_reclaimable_gb=rec_gb
    )



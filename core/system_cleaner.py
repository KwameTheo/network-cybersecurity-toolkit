def safe_clean_directory(dir_path: str, delete_subdirs: bool = True) -> tuple[int, int, int, List[str]]:
    """
    Safely deletes files inside a folder without deleting the root folder itself.
    Skips locked files gracefully.
    Returns: (deleted_count, failed_count, freed_bytes, logs)
    """
    if not os.path.exists(dir_path):
        return 0, 0, 0, [f"[*] Path does not exist: {dir_path}"]

    deleted = 0
    failed = 0
    freed_bytes = 0
    logs: List[str] = []

    for item in os.listdir(dir_path):
        item_path = os.path.join(dir_path, item)
        if os.path.isfile(item_path) or os.path.islink(item_path):
            try:
                sz = os.path.getsize(item_path)
                os.remove(item_path)
                freed_bytes += sz
                deleted += 1
            except (PermissionError, OSError):
                failed += 1
        elif os.path.isdir(item_path) and delete_subdirs:
            try:
                # Calculate size before tree removal
                for root, _, files in os.walk(item_path):
                    for f in files:
                        try:
                            freed_bytes += os.path.getsize(os.path.join(root, f))
                            deleted += 1
                        except OSError:
                            pass
                shutil.rmtree(item_path, ignore_errors=False)
            except (PermissionError, OSError):
                failed += 1

    return deleted, failed, freed_bytes, logs


def execute_disk_cleanup(selected_categories: List[str]) -> CleanupExecutionResult:
    """
    Executes safe cleanup across the chosen category keys.
    """
    targets = get_target_cleanup_directories()
    total_deleted = 0
    total_failed = 0
    total_freed_bytes = 0
    all_logs: List[str] = [f"[*] Starting system disk cleanup for {len(selected_categories)} categories..."]

    for cat_key in selected_categories:
        if cat_key not in targets:
            continue
        info = targets[cat_key]
        p = info["path"]
        name = info["name"]

        all_logs.append(f"[*] Pruning '{name}' ({p})...")
        d, f, b, _ = safe_clean_directory(p)
        total_deleted += d
        total_failed += f
        total_freed_bytes += b
        all_logs.append(f"    -> Removed {d} files ({b / (1024**2):.2f} MB freed). Skipped {f} locked files.")

    freed_mb = round(total_freed_bytes / (1024 ** 2), 2)
    all_logs.append(f"[+] Cleanup Complete! Total Freed: {freed_mb} MB ({total_deleted} files removed).")
    logger.info(f"Disk cleanup finished: {freed_mb} MB freed.")

    return CleanupExecutionResult(
        deleted_files=total_deleted,
        failed_files=total_failed,
        freed_bytes=total_freed_bytes,
        freed_mb=freed_mb,
        logs=all_logs
    )

def get_target_cleanup_directories() -> Dict[str, Dict[str, str]]:
    """Returns standardized paths for reclaimable Windows temporary caches."""
    win_dir = os.environ.get("SystemRoot", "C:\\Windows")
    local_app_data = os.environ.get("LOCALAPPDATA", "")
    program_data = os.environ.get("ProgramData", "C:\\ProgramData")
    user_temp = os.environ.get("TEMP", os.path.join(local_app_data, "Temp"))

    return {
        "user_temp": {
            "name": "User Temporary Files",
            "path": user_temp,
            "desc": "Scratch files, temporary installer extraction caches, and browser temp files."
        },
        "system_temp": {
            "name": "Windows System Temp",
            "path": os.path.join(win_dir, "Temp"),
            "desc": "OS-level background services scratch files and system update logs."
        },
        "win_update_cache": {
            "name": "Windows Update Download Cache",
            "path": os.path.join(win_dir, "SoftwareDistribution", "Download"),
            "desc": "Downloaded update packages (.cab / .msu) that have already been installed."
        },
        "crash_dumps": {
            "name": "Windows Crash Dumps (WER)",
            "path": os.path.join(program_data, "Microsoft", "Windows", "WER", "ReportArchive"),
            "desc": "Memory minidumps (.dmp) created when applications or kernel services crash."
        },
        "user_crash_dumps": {
            "name": "User Application Crash Dumps",
            "path": os.path.join(local_app_data, "CrashDumps"),
            "desc": "User-mode crash reports generated by desktop software."
        },
        "thumbnail_cache": {
            "name": "Windows Thumbnail Cache",
            "path": os.path.join(local_app_data, "Microsoft", "Windows", "Explorer"),
            "desc": "Cached image and video explorer preview thumbnails."
        }
    }


